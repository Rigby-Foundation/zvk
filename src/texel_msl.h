/* Packed texel conversion runs on Metal. Tags match enum zvk_format_type. */
static const char zvk_texel_msl[] =
    "enum zvk_fmt { F_UNORM, F_SNORM, F_UINT, F_SINT, F_FLOAT, F_SRGB, F_UFLOAT, F_SHARED };\n"
    "struct zvk_info { uint4 extent; uint4 format; };\n"
    "uint zvk_ioffset(zvk_info m,uint3 p) {\n"
    "    if(any(p>=m.extent.xyz)) return 0xffffffffu;\n"
    "    return ((p.z*m.extent.y+p.y)*m.extent.x+p.x)*m.format.x+m.extent.w;\n"
    "}\n"
    "uint zvk_bits(const device uchar *b,uint shift,uint bits) {\n"
    "    uint v=0;\n"
    "    for(uint i=0;i<bits;i++) v|=uint((b[(shift+i)/8]>>((shift+i)%8))&1u)<<i;\n"
    "    return v;\n"
    "}\n"
    "uint zvk_round_shift(uint v,uint s) {\n"
    "    if(!s)return v; if(s>31)return 0;\n"
    "    uint q=v>>s,mask=(1u<<s)-1u,midpoint=1u<<(s-1);\n"
    "    return q+uint((v&mask)>midpoint||((v&mask)==midpoint&&(q&1u)));\n"
    "}\n"
    "uint zvk_float_pack(float x,uint bits,bool sign) {\n"
    "    uint raw=as_type<uint>(x),n=bits-5u-uint(sign),s=sign?(raw>>31)<<(bits-1):0u;\n"
    "    uint e=(raw>>23)&255u,v=raw&0x7fffffu;\n"
    "    if(!sign&&(raw>>31)&&!(e==255u&&v))return 0u;\n"
    "    if(e==255u)return s|(31u<<n)|(v?1u<<(n-1):0u);\n"
    "    int adjusted=int(e)-112;\n"
    "    if(adjusted>=31)return s|(31u<<n);\n"
    "    if(adjusted<=0)return s|zvk_round_shift(v|(e?0x800000u:0u),uint(24-int(n)-adjusted));\n"
    "    return s|((uint(adjusted)<<n)+zvk_round_shift(v,23u-n));\n"
    "}\n"
    "float zvk_float_unpack(uint raw,uint bits,bool sign) {\n"
    "    uint n=bits-5u-uint(sign),e=(raw>>n)&31u,m=raw&((1u<<n)-1u);\n"
    "    float v=e==31u?as_type<float>(0x7f800000u|(m?0x400000u:0u)):\n"
    "            e==0u?ldexp(float(m),-14-int(n)):ldexp(1.0f+float(m)/float(1u<<n),int(e)-15);\n"
    "    return sign&&(raw>>(bits-1))?-v:v;\n"
    "}\n"
    "uint4 zvk_iread(const device uint *buffer,uint bytes,zvk_info m,uint3 p) {\n"
    "    uint o=zvk_ioffset(m,p),bpp=m.format.x,t=m.format.y&255u;\n"
    "    if(o>bytes||bpp>bytes-o)return uint4(0);\n"
    "    const device uchar *b=reinterpret_cast<const device uchar *>(buffer)+o;\n"
    "    uint4 v=uint4(0,0,0,(t==F_UINT||t==F_SINT)?1u:as_type<uint>(1.0f));\n"
    "    if(t==F_SHARED) {\n"
    "        int e=int(zvk_bits(b,27,5))-24;\n"
    "        for(uint c=0;c<3;c++)v[c]=as_type<uint>(ldexp(float(zvk_bits(b,c*9,9)),e));\n"
    "        return v;\n"
    "    }\n"
    "    for(uint c=0;c<4;c++) {\n"
    "        uint bits=(m.format.z>>(8*c))&255u,shift=(m.format.w>>(8*c))&255u;\n"
    "        if(!bits)continue;\n"
    "        uint raw=zvk_bits(b,shift,bits),mask=bits==32u?0xffffffffu:(1u<<bits)-1u;\n"
    "        if(t==F_UINT)v[c]=raw;\n"
    "        else if(t==F_SINT)v[c]=bits==32u?raw:((raw&(1u<<(bits-1)))?(raw|~mask):raw);\n"
    "        else {\n"
    "            float f=0;\n"
    "            if(t==F_FLOAT)f=bits==32u?as_type<float>(raw):zvk_float_unpack(raw,bits,true);\n"
    "            else if(t==F_UFLOAT)f=zvk_float_unpack(raw,bits,false);\n"
    "            else if(t==F_SNORM) {\n"
    "                int s=(raw&(1u<<(bits-1)))?as_type<int>(raw|~mask):int(raw);\n"
    "                f=max(float(s)/float(mask>>1),-1.0f);\n"
    "            } else {\n"
    "                f=float(raw)/float(mask);\n"
    "                if(t==F_SRGB&&c<3)f=f<=0.04045f?f/12.92f:pow((f+0.055f)/1.055f,2.4f);\n"
    "            }\n"
    "            v[c]=as_type<uint>(f);\n"
    "        }\n"
    "    }\n"
    "    return v;\n"
    "}\n"
    "void zvk_iwrite(device uint *buffer,uint bytes,zvk_info m,uint3 p,uint4 v) {\n"
    "    uint o=zvk_ioffset(m,p),bpp=m.format.x,t=m.format.y&255u;\n"
    "    if(o>bytes||bpp>bytes-o)return;\n"
    "    uchar texel[16];\n"
    "    for(uint i=0;i<16;i++)texel[i]=0;\n"
    "    for(uint c=0;c<4;c++) {\n"
    "        uint bits=(m.format.z>>(8*c))&255u,shift=(m.format.w>>(8*c))&255u;\n"
    "        if(!bits)continue;\n"
    "        uint mask=bits==32u?0xffffffffu:(1u<<bits)-1u,raw=v[c];\n"
    "        if(t==F_FLOAT)raw=bits==32u?v[c]:zvk_float_pack(as_type<float>(v[c]),bits,true);\n"
    "        else if(t==F_UFLOAT)raw=zvk_float_pack(as_type<float>(v[c]),bits,false);\n"
    "        else "
    "if(t==F_SNORM)raw=as_type<uint>(int(round(clamp(as_type<float>(v[c]),-1.0f,1.0f)*float(mask>>"
    "1))))&mask;\n"
    "        else "
    "if(t==F_UNORM||t==F_SRGB)raw=uint(round(clamp(as_type<float>(v[c]),0.0f,1.0f)*float(mask)));\n"
    "        else raw&=mask;\n"
    "        for(uint "
    "bit=0;bit<bits;bit++)if(raw&(1u<<bit))texel[(shift+bit)/8]|=uchar(1u<<((shift+bit)%8));\n"
    "    }\n"
    "    device uchar *b=reinterpret_cast<device uchar *>(buffer)+o;\n"
    "    for(uint i=0;i<bpp;i++)b[i]=texel[i];\n"
    "}\n"
    "\n";
