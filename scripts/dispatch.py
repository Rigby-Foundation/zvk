"""Generate the scoped dispatch table from the implemented API entry points."""
from pathlib import Path
import os,re
root=Path(__file__).resolve().parents[1]
entries={'vkGetInstanceProcAddr':('GLOBAL','0'),'vkGetDeviceProcAddr':('DEVICE','0')}
swapchain={'vkAcquireNextImageKHR','vkCreateSwapchainKHR','vkDestroySwapchainKHR','vkGetSwapchainImagesKHR','vkQueuePresentKHR'}
properties2={'vkGetPhysicalDeviceFeatures2KHR','vkGetPhysicalDeviceProperties2KHR','vkGetPhysicalDeviceFormatProperties2KHR','vkGetPhysicalDeviceImageFormatProperties2KHR','vkGetPhysicalDeviceQueueFamilyProperties2KHR','vkGetPhysicalDeviceMemoryProperties2KHR','vkGetPhysicalDeviceSparseImageFormatProperties2KHR'}
for source in sorted((root/'src').glob('*.c')):
    if source.name=='dispatch.c':continue
    for name,args in re.findall(r'VKAPI_ATTR\s+\w+\s+VKAPI_CALL\s+(vk\w+)\(([^)]*)\)',source.read_text()):
        first=re.match(r'\s*(\w+)\b',args)
        first_type=first.group(1) if first else ''
        scope='DEVICE' if first_type in {'VkDevice','VkQueue','VkCommandBuffer'} else 'INSTANCE' if first_type in {'VkInstance','VkPhysicalDevice'} else 'GLOBAL'
        flag='ZVK_EXT_HOST_QUERY_RESET' if name=='vkResetQueryPoolEXT' else 'ZVK_EXT_PROPERTIES2' if name in properties2 else 'ZVK_EXT_SWAPCHAIN' if name in swapchain else 'ZVK_EXT_HEADLESS' if name=='vkCreateHeadlessSurfaceEXT' else 'ZVK_EXT_ZWM' if name=='vkCreateZwmSurfaceSIC' else 'ZVK_EXT_SURFACE' if 'Surface' in name else '0'
        entries[name]=(scope,flag)
data='/* Generated by scripts/dispatch.py. */\n'+''.join('    {"%s", (PFN_vkVoidFunction)%s, %s, %s},\n'%(name,name,scope,flag) for name,(scope,flag) in sorted(entries.items()))
target=root/'src/procs.inc'
if not target.exists() or target.read_text()!=data:
    temp=target.with_suffix('.tmp.%d'%os.getpid());temp.write_text(data);temp.replace(target)
else:
    target.touch()
